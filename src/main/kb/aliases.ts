const INDEX = new Map<string, Set<string>>()
for (const group of GROUPS) {
  for (const term of group) {
    const others = group.filter((x) => x !== term)
    const bucket = INDEX.get(term) ?? new Set<string>()
    for (const o of others) bucket.add(o)
    INDEX.set(term, bucket)
  }
}

/**
 * Дополнительные термины для текста. Короткие аббревиатуры ищем только по
 * границам слова: иначе «рс» находится внутри «версия» и тянет за собой
 * регистры сведений на каждом шагу.
 */
export function expandTerms(text: string): string {
  const low = ' ' + (text ?? '').toLowerCase().replace(/ё/g, 'е') + ' '
  const add = new Set<string>()
  for (const [term, syns] of INDEX) {
    const hit =
      term.length <= 3
        ? new RegExp(`(^|[\\s.,:;!?()"'-])${term}([\\s.,:;!?()"'-]|$)`).test(low)
        : low.includes(term)
    if (hit) for (const s of syns) add.add(s)
  }
  return [...add].join(' ')
}
