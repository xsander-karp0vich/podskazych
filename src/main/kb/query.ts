/**
 * Что искать в базе знаний, когда пользователь просит подсказку.
 *
 * Не весь транскрипт. Проверено на логах двух созвонов, 11 вопросов: поиск по
 * последним сорока строкам находил ответы на ПРЕДЫДУЩИЕ вопросы — 5 попаданий
 * из 11, и модели уходил контекст совсем не по теме. По последней
 * содержательной реплике — 11 из 11. Две последние реплики дали 10 из 11:
 * предыдущий вопрос перебивает текущий чаще, чем помогает дособрать его.
 */

/**
 * Вежливые и служебные слова, из которых целиком состоят реплики-связки.
 * Совпадение — только по границе слова: иначе «Так, а что такое СКД?» терялось
 * из-за «так», а «Дата документа…» — из-за «да».
 */
const FILLER =
  /^(?:(?:спасибо|благодарю|давайте?|да|ага|угу|ок(?:ей)?|хорошо|отлично|понял[аи]?|понятно|ясно|так|ну|а|вот|вс[её])(?![\p{L}\p{N}])[\s,.!?…—-]*)+/iu

export function isTrivialLine(text: string): boolean {
  const rest = text.trim().replace(FILLER, '').trim()
  if (!rest) return true
  // Короткий, но настоящий вопрос — «Что за РН?», «А СКД?» — порогом длины не режем.
  if (rest.includes('?') || /[A-ZА-ЯЁ]{2,}/.test(rest)) return false
  return rest.replace(/[^\p{L}\p{N} ]/gu, '').trim().length < 12
}

/**
 * Вопрос собеседника, если он содержательный. Иначе — последняя содержательная
 * реплика транскрипта от кого угодно: так работает и проверка «сам себе
 * зачитываю вопросы», где реплик собеседника нет вовсе.
 */
export function kbQueryFor(question: string, transcript: string): string {
  if (question && !isTrivialLine(question)) return question
  const lines = transcript
    .split('\n')
    .map((l) => l.replace(/^\[[^\]]*\]\s*/, '').trim())
    .filter(Boolean)
  for (let i = lines.length - 1; i >= 0; i--) {
    const line = lines[i]!
    if (!isTrivialLine(line)) return line
  }
  return question || transcript
}
