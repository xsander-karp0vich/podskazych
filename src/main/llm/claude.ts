import Anthropic from '@anthropic-ai/sdk'
import { ProxyAgent, setGlobalDispatcher } from 'undici'

/**
 * Node-овский fetch (undici) НЕ читает системный прокси Windows и не смотрит
 * на HTTP_PROXY сам по себе — в отличие от Chromium. Без этого запрос к Клоду
 * уходит мимо прокси и висит до таймаута при «включённом VPN».
 */
export function configureProxy(): string | null {
  const url = process.env.HTTPS_PROXY ?? process.env.HTTP_PROXY ?? null
  if (!url) return null
  setGlobalDispatcher(new ProxyAgent(url))
  return url
}

export interface SuggestParams {
  /**
   * Расшифровка и вопрос. Найденное во встроенной базе main уже поставил в начало —
   * модели не нужно ходить за ним самой. Меняется на каждом вопросе, поэтому идёт ПОСЛЕ точки кэша.
   */
  transcript: string
  onText: (delta: string) => void
  signal?: AbortSignal
}

const SYSTEM = `Ты — суфлёр на рабочем созвоне. Тебе приходит расшифровка разговора; \
реплики собеседника помечены [Собеседник], твоего пользователя — [Я].

Твоя задача: дать пользователю то, что он скажет вслух своими словами.

Правила:
- 3-5 коротких тезисов, не абзац. Первый тезис — прямой ответ на вопрос.
- Пиши по-русски. Термины домена оставляй как есть.
- Если перед расшифровкой есть записи из базы знаний и они подходят — опирайся на них.
- Если данных не хватает, так и скажи одной строкой. Не выдумывай цифры,
  названия и сроки: пользователь произнесёт это вслух перед коллегами.
- Код и запросы — только блоком с тремя обратными кавычками и языком: \`\`\`1c, \`\`\`sql.
- Никаких вступлений и вежливых оборотов. Только суть.`

export interface ScreenParams {
  /** снимки в порядке съёмки: base64 без префикса data: */
  images: Array<{ data: string; mediaType: 'image/jpeg' | 'image/png' }>
  /** пояснение к серии: несколько снимков — одна задача, склеенная прокруткой */
  intro?: string
  /** что именно спросить; пусто — «объясни, что на экране» */
  question: string
  /** последние реплики: без них модель не понимает, к чему вопрос */
  transcript: string
  onText: (delta: string) => void
  signal?: AbortSignal
}

/**
 * Вопрос к снимку, когда пользователь ничего не ввёл, — самый частый случай на live coding.
 * «Объясни коротко» последней строкой спорило бы с форматом решения выше, поэтому развилка — прямо здесь.
 */
export const SCREEN_DEFAULT_QUESTION =
  'Что на экране? Если там задача на код или запрос — дай решение в формате выше, иначе объясни коротко.'

