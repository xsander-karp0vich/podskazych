export class ClaudeSuggester {
  private client: Anthropic
  private model: string

  constructor(opts: { apiKey?: string; model?: string } = {}) {
    // Без apiKey SDK сам поднимет ANTHROPIC_API_KEY или профиль `ant auth login`.
    this.client = opts.apiKey ? new Anthropic({ apiKey: opts.apiKey }) : new Anthropic()
    this.model = opts.model ?? 'claude-opus-5'
  }

  /**
   * Разбор снимка экрана.
   *
   * Кэширование префикса здесь бесполезно: картинка каждый раз новая и стоит
   * до последнего блока. И честно про скорость — снимок отвечает медленнее
   * текста: кодирование, загрузка нескольких сотен килобайт и префилл
   * визуальных токенов дают заметно больший TTFT.
   */
  async describeScreen(p: ScreenParams): Promise<string> {
    let full = ''

    const stream = this.client.messages.stream(
      {
        model: this.model,
        // Решение задачи со снимка — несколько кусков кода с пояснениями: 1024 токенов на него не хватало.
        max_tokens: 4096,
        output_config: { effort: 'low' },
        system: SCREEN_SYSTEM,
        messages: [
          {
            role: 'user',
            content: [
              // Картинки идут ПЕРЕД текстом и в порядке съёмки: так модель сначала
              // смотрит, потом читает вопрос.
              ...p.images.map((img) => ({
                type: 'image' as const,
                source: { type: 'base64' as const, media_type: img.mediaType, data: img.data },
              })),
              {
                type: 'text',
                text:
                  (p.intro ? `${p.intro}\n\n` : '') +
                  (p.transcript ? `Последние реплики разговора:\n${p.transcript}\n\n` : '') +
                  (p.question || SCREEN_DEFAULT_QUESTION),
              },
            ],
          },
        ],
      },
      { signal: p.signal },
    )

    stream.on('text', (delta) => {
      full += delta
      p.onText(delta)
    })

    await stream.finalMessage()
    return full
  }

  async suggest(p: SuggestParams): Promise<string> {
    // Точка кэша — на системном промпте: он одинаковый у всех вопросов созвона.
    const system: Anthropic.TextBlockParam[] = [{ type: 'text', text: SYSTEM, cache_control: { type: 'ephemeral' } }]

    const stream = this.client.messages.stream(
      {
        model: this.model,
        max_tokens: 1024, // суфлёру нужны тезисы, а не эссе
        output_config: { effort: 'low' }, // латентность важнее глубины
        system,
        messages: [
          {
            role: 'user',
            content: `Расшифровка разговора:\n${p.transcript}\n\nПодскажи ответ на последний вопрос собеседника.`,
          },
        ],
      },
      { signal: p.signal },
    )

    let full = ''
    stream.on('text', (delta) => {
      full += delta
      p.onText(delta)
    })
    await stream.finalMessage()
    return full
  }
}
