import type { KbHit } from '../kb/search'

/**
 * Проверка подсказки вторым агентом.
 *
 * Быстрый ответ на созвоне пишется за секунды, и модель в нём иногда уверенно
 * ошибается. Пример из реального лога 11 сентября: «в управляемом режиме
 * эскалации нет» — а в базе знаний прямо написано обратное. Проверяющий берёт
 * готовый ответ, сверяет утверждения с базой и своими знаниями и возвращает
 * либо «верно», либо короткие уточнения, которые панель покажет под ответом.
 *
 * Главное правило — молчать, если не уверен. Ложная тревога посреди созвона
 * хуже тишины: пользователь поправит себя там, где был прав.
 */

/**
 * skipped — автоматическая проверка устарела в очереди: уже задан следующий вопрос;
 * cancelled — второго агента выключили посреди проверки.
 */
export type VerifyStatus = 'checking' | 'ok' | 'issues' | 'unclear' | 'error' | 'skipped' | 'cancelled'

/** Что второй агент делает прямо сейчас — подпись в его окне. */
export type VerifyStage = 'queued' | 'working' | 'thinking' | 'searching' | 'writing'

export interface VerifyUpdate {
  requestId: number
  status: VerifyStatus
  /** уточнения по одному на строку; пусто, если статус не 'issues' */
  notes: string[]
  tookMs?: number
  /** когда проверка началась: от этого момента окно ведёт счётчик */
  startedAt?: number
  stage?: VerifyStage
  /** что второй агент успел написать; в итоговом событии — весь его ответ */
  text?: string
  /** вопросы записей базы, с которыми он сверялся */
  refs?: string[]
  error?: string
}

export const VERIFY_SYSTEM = `Ты проверяешь подсказку, которую суфлёр только что дал пользователю на рабочем созвоне по 1С. Пользователь произнесёт её вслух перед коллегами.

Ищи только фактические ошибки, за которые пользователю будет неловко: неверный механизм платформы, несуществующий метод или свойство, неправильная цифра или порядок действий, утверждение, которое прямо противоречит базе знаний.

Не считай ошибкой стиль, краткость, неполноту, «можно было добавить» и спорные формулировки без фактической ошибки.

Если подсказка — решение задачи с кодом или запросом, ищи ошибки, из-за которых решение не заработает или не выполнит условие: синтаксис, несуществующее поле или таблица, неверное соединение или отбор, пропущенное требование условия. Другой способ решить ту же задачу ошибкой не считай.

Опирайся сначала на записи из базы знаний, если они относятся к вопросу, затем на свои знания платформы 1С:Предприятие 8.3. Если сомневаешься — не отмечай: ложная тревога на созвоне хуже, чем пропущенная неточность.

Формат ответа — строго одно из двух.
Если ошибок нет — одно слово: ВЕРНО
Если есть — от одной до трёх строк, каждая начинается с «⚠ » и одним предложением говорит, что неверно и как на самом деле, не длиннее 30 слов.

Никаких вступлений, пояснений и других строк.`

export function buildVerifyPrompt(question: string, answer: string, hits: KbHit[], images = 0): string {
  const kb = hits.length
    ? hits
        .map((h, i) => {
          const parts = [`[${i + 1}] ${h.question}`]
          if (h.short) parts.push(`Суть: ${h.short}`)
          if (h.anchors) parts.push(`Опорные пункты: ${h.anchors}`)
          return parts.join('\n')
        })
        .join('\n\n')
    : 'Записей по этому вопросу в базе нет.'

  const shot =
    images > 1
      ? `Снимки экрана с условием задачи — выше, в порядке съёмки: это одно условие, разрезанное прокруткой. Сверяй решение с ним.

`
      : images === 1
        ? `Снимок экрана с условием задачи — выше. Сверяй решение с условием на снимке.

`
        : ''
  return `${shot}Вопрос:
${question || '(вопрос не выделен — ориентируйся на подсказку)'}

Подсказка суфлёра:
${answer}

База знаний:
${kb}`
}

/**
 * Разбор ответа проверяющего. Всё, что не укладывается в формат, — «неясно»:
 * такое панель не показывает, чтобы сбой проверки не выглядел как предупреждение.
 */
export function parseVerdict(text: string): { status: 'ok' | 'issues' | 'unclear'; notes: string[] } {
  const lines = text
    .split('\n')
    // Оформление, которое модель иногда добавляет: жирный, маркер списка, нумерация.
    .map((l) => l.replace(/\*\*/g, '').trim().replace(/^(?:[-*•]|\d+[.)])\s*/, '').trim())
    .filter(Boolean)
  const notes = lines
    .filter((l) => l.startsWith('⚠'))
    .map((l) => `⚠ ${l.replace(/^⚠\s*/, '')}`)
    .slice(0, 3)
  const isOk = (l: string | undefined) => /^верно[.!]?$/i.test(l ?? '')
  // С веб-поиском вердикт приходит последним: сначала «Проверю…», потом ответ.
  const saysOk = isOk(lines[0]) || isOk(lines[lines.length - 1])

  if (notes.length && !saysOk) return { status: 'issues', notes }
  if (saysOk && !notes.length) return { status: 'ok', notes: [] }
  return { status: 'unclear', notes: [] }
}
