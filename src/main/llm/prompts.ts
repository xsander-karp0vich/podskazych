/**
 * Промпты суфлёра, общие для всех провайдеров.
 *
 * Текст подобран и замерен на Claude Code. Держим его в одном месте: раньше у каждого
 * транспорта была своя копия с припиской «при правке — править оба», и копии рано или
 * поздно разошлись бы — один провайдер отвечал бы в другом формате.
 *
 * Модуль чистый (без electron и node): его импортируют протокольные модули и тесты
 * под голым Node (см. tests/README.md).
 */

/** Встроенный системный промпт суфлёра: уходит, если пользователь не задал свой. */
export const SUGGEST_SYSTEM = `Ты — суфлёр на рабочем созвоне. Тебе приходит расшифровка разговора:
реплики собеседника помечены [Собеседник], реплики пользователя — [Я].

Дай пользователю то, что он скажет вслух своими словами.

Правила:
- 3-5 коротких тезисов, не абзац. Первый тезис — прямой ответ на вопрос.
- Пиши по-русски. Термины домена оставляй как есть.
- Не выдумывай цифры, названия и сроки: пользователь произнесёт это вслух
  перед коллегами. Если данных нет — так и скажи одной строкой.
- Код и запросы — только блоком с тремя обратными кавычками и языком: \`\`\`1c, \`\`\`sql.
- Никаких вступлений, вежливых оборотов и встречных вопросов. Только суть.`

/**
 * Добавка к промпту, когда размышления выключены: без неё модель начинает
 * рассуждать прямо в ответе, и первый тезис тонет во вступлении.
 * У Claude — только для Haiku 4.5: на Opus 5 правило «не рассуждай» по документации
 * усиливает протечку тегов мышления, а мышление там больше не выключается.
 */
export const NO_THINKING_RULE = '\n- Не рассуждай в ответе, сразу тезисы.'

/**
 * Прогревочный вопрос: нужен только чтобы оплатить старт сессии до созвона.
 * Ответ выбрасывается, поэтому вопрос — самый короткий, какой модель не проигнорирует.
 */
export const WARMUP_PROMPT = 'Ответь одним словом: готов.'

/**
 * Системный промпт сессии подсказок. Свой промпт пользователя важнее встроенного;
 * правило «не рассуждай» добавляется только к встроенному — свой промпт не дописываем:
 * пользователь мог сознательно попросить рассуждения.
 *
 * context — блок материалов пользователя (contextBlock в @shared/contextFiles) или пусто.
 * Дописывается к любому из промптов: резюме нужно и со встроенным, и со своим. Блок входит
 * в сам промпт, поэтому смена файлов меняет промпт — и провайдеры открывают новую сессию
 * тем же сравнением, что и при смене своего промпта.
 */
export function suggestSystemPrompt(custom: string | undefined, noThinkingRule = false, context = ''): string {
  return (custom?.trim() || SUGGEST_SYSTEM + (noThinkingRule ? NO_THINKING_RULE : '')) + context
}
